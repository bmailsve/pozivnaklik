// Downloads the Google Fonts the designs use into src/fonts and writes src/styles/fonts.css,
// so the site serves its own fonts (no render-blocking request to another server, cached for a year).
// Run again only when a font family is added: npm run fonts
import { mkdir, writeFile, rm } from "node:fs/promises";
import { createHash } from "node:crypto";

const FAMILIES = "family=Baloo+2:wght@500;700&family=Bree+Serif&family=Lilita+One&family=Bebas+Neue&family=Bodoni+Moda:ital,opsz,wght@0,6..96,400..700;1,6..96,400..700&family=Cinzel:wght@400;600&family=Cinzel+Decorative:wght@400;700&family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400;1,500&family=Fredoka:wght@500;600&family=IBM+Plex+Mono:wght@400;500&family=Caveat:wght@500;600&family=Gilda+Display&family=Great+Vibes&family=Jost:wght@300;400;500;600;700&family=Lora:ital,wght@0,400;0,500;0,600;0,700;1,400&family=Manrope:wght@400;500;600;700&family=Nunito:wght@400;600;700;800&family=Mrs+Saint+Delafield&family=Marcellus&family=Parisienne&family=Pinyon+Script&family=Playfair+Display:ital,wght@0,500;0,700;1,500&family=Quicksand:wght@400;500;600";
// Serbian needs latin-ext (č ć š ž đ); cyrillic is kept for hosts who write in ćirilica.
const SUBSETS = new Set(["latin", "latin-ext", "cyrillic", "cyrillic-ext"]);
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

const css = await (await fetch(`https://fonts.googleapis.com/css2?${FAMILIES}&display=swap`, { headers: { "User-Agent": UA } })).text();
const blocks = [...css.matchAll(/\/\* ([a-z-]+) \*\/\s*(@font-face \{[^}]+\})/g)];
if (!blocks.length) throw new Error("Google Fonts returned no @font-face rules");

await rm(new URL("../src/fonts/", import.meta.url), { recursive: true, force: true });
await mkdir(new URL("../src/fonts/", import.meta.url), { recursive: true });
const files = new Map();
let out = "/* Self-hosted Google Fonts (SIL Open Font License). Generated by scripts/fetch-fonts.mjs. */\n";
for (const [, subset, face] of blocks) {
  if (!SUBSETS.has(subset)) continue;
  const url = face.match(/url\((https:[^)]+)\)/)[1];
  if (!files.has(url)) {
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    const fam = face.match(/font-family: '([^']+)'/)[1].toLowerCase().replace(/[^a-z0-9]+/g, "-");
    const name = `${fam}-${subset}-${createHash("sha1").update(buf).digest("hex").slice(0, 8)}.woff2`;
    await writeFile(new URL(`../src/fonts/${name}`, import.meta.url), buf);
    files.set(url, name);
  }
  out += `/* ${subset} */\n` + face.replace(url, `../fonts/${files.get(url)}`) + "\n";
}
await writeFile(new URL("../src/styles/fonts.css", import.meta.url), out);
console.log(`${files.size} font files, ${out.length} bytes of CSS`);
